def _grid_shape(n: int) -> tuple[int, int]:
    """Return (nrows, ncols) for a roughly-square grid of n panels."""
    ncols = math.ceil(math.sqrt(n))
    nrows = math.ceil(n / ncols)
    return nrows, ncols


def _heatmap_panel(
    ax: plt.Axes,
    matrix: "pd.DataFrame",
    title: str,
    annot: bool = True,
) -> None:
    """Draw a single p-value heatmap on ax."""
    mask = np.isnan(matrix.values)
    sns.heatmap(
        matrix,
        ax=ax,
        mask=mask,
        annot=annot,
        fmt=".3f",
        cmap=_CMAP,
        vmin=0.0,
        vmax=_VMAX,
        linewidths=0.4,
        linecolor="white",
        cbar=True,
        cbar_kws={"shrink": 0.4},
        annot_kws={"size": 15},
    )
    ax.set_aspect(0.5, adjustable='box')
    ax.set_title(title, fontsize=14, fontweight="bold", pad=4)
    ax.tick_params(axis="both", labelsize=12)
    # Abbreviate tick labels for display
    abbrev_x_labels = [_abbreviate_fold_type(label.get_text()) for label in ax.get_xticklabels()]
    abbrev_y_labels = [_abbreviate_fold_type(label.get_text()) for label in ax.get_yticklabels()]
    ax.set_xticklabels(abbrev_x_labels, rotation=0)
    ax.set_yticklabels(abbrev_y_labels, rotation=0)
    ax.set_xlabel("")
    ax.set_ylabel("")


# ─── Main plot function ───────────────────────────────────────────────────────


def plot_pvalue_summary(
    metrics_df: pl.DataFrame,
    phase: str,
    metric: str,
    test_col: str,
    col_label: str,
) -> "pd.DataFrame | None":
    """
    Build a grid of per-model p-value heatmaps plus a summary (average) heatmap.

    Returns the fine-tuned summary matrix for LaTeX table generation (ttest only).

    Args:
        metrics_df: Per-fold metric DataFrame (output of prepare_per_fold_metrics).
        phase:      "test" or "holdout".
        metric:     Metric name (e.g. "f1").
        test_col:   Column in run_pairwise_tests output ("P-Value" or "Wilcoxon P-Value").
        col_label:  Short label used in file name and titles ("ttest" or "wilcoxon").
    """
    models = sorted(metrics_df["model"].unique().to_list())
    if not models:
        return None

    # Union of all fold types across all models - restrict to the 5 primary CV strategies
    _PRIMARY_PREFIXES = (
        "K-Fold CV",
        "Random Growing Window CV",
        "Random LOO Block CV",
        "Temporal Growing Window CV",
        "Temporal LOO Block CV",
    )
    all_fold_types = sorted(
        ft for ft in metrics_df["fold_type"].unique().to_list()
        if any(ft.startswith(p) for p in _PRIMARY_PREFIXES)
    )
    n_ft = len(all_fold_types)
    if n_ft < 2:
        print(f"  [{col_label}] Need ≥2 fold types; skipping.")
        return None

    # Collect per-model p-value matrices
    model_matrices: dict[str, "pd.DataFrame"] = {}
    for model in models:
        results = run_pairwise_tests(metrics_df, model, metric=metric)
        if results.empty:
            continue
        # ttest_rel / wilcoxon return NaN when all pairwise differences are zero
        # (zero-variance case: model performed identically across every fold).
        # Semantically this is "not significant" (p=1.0), so fill NaN → 1.0 to
        # distinguish "tested, identical" from "never tested" (left as NaN).
        results = results.copy()
        results[test_col] = results[test_col].fillna(1.0)
        mat = _build_symmetric_matrix(results, all_fold_types, test_col, diag_val=float("nan"))
        for ft in all_fold_types:
            mat.at[ft, ft] = 1.0  # trivial diagonal: comparing a fold type with itself
        model_matrices[model] = mat

    valid_models = list(model_matrices.keys())
    if not valid_models:
        print(f"  [{col_label}] No valid model pairs; skipping.")
        return None

    # Summary: nanmean across all model matrices
    stacked = np.stack([model_matrices[m].values for m in valid_models], axis=0)
    # Diagonal values are 1.0 (trivial) - replace with NaN before averaging so
    # diagonal is excluded from the summary mean and rendered as NaN (white).
    diag_mask = np.eye(n_ft, dtype=bool)
    stacked[:, diag_mask] = np.nan
    summary_values = np.nanmean(stacked, axis=0)
    # Restore diagonal = 1.0 for visual consistency
    np.fill_diagonal(summary_values, 1.0)

    import pandas as pd
    summary_mat = pd.DataFrame(summary_values, index=all_fold_types, columns=all_fold_types)

    # ── Figure layout ─────────────────────────────────────────────────────────
    n_panels = len(valid_models) + 1  # +1 for summary
    nrows, ncols = _grid_shape(n_panels)

    cell_size = max(2.8, n_ft * 0.7)
    subplot_size = cell_size * n_ft * 0.4 + 2.5
    fig, axes = plt.subplots(
        nrows, ncols,
        figsize=(ncols * subplot_size, nrows * subplot_size),
        squeeze=False,
    )

    test_label = "Paired T-test" if col_label == "ttest" else "Wilcoxon Signed-Rank"
    fig.suptitle(
        f"P-Value Comparison by Fold Type - {test_label} ({metric.upper()}, {phase})",
        fontsize=18,
        fontweight="bold",
        y=0.995,
    )

    # Per-model heatmaps
    for idx, model in enumerate(valid_models):
        row, col = divmod(idx, ncols)
        ax = axes[row][col]
        _heatmap_panel(ax, model_matrices[model], title=model)

    # Summary heatmap (last occupied cell)
    sum_idx = len(valid_models)
    sum_row, sum_col = divmod(sum_idx, ncols)
    _heatmap_panel(axes[sum_row][sum_col], summary_mat, title="Average across models", annot=True)

    # Hide unused axes
    for idx in range(n_panels, nrows * ncols):
        r, c = divmod(idx, ncols)
        axes[r][c].set_visible(False)

    plt.tight_layout()
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = PLOTS_DIR / f"{col_label}_pvalue_heatmaps_{phase}.png"
    fig.savefig(out_path, dpi=600, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out_path}")

    # Standalone summary figures (ttest only - one clean heatmap per phase/family)
    finetuned_mat = None
    if col_label == "ttest":
        import pandas as pd

        def _save_summary(mat: "pd.DataFrame", label: str) -> None:
            cell_size_sum = max(3.0, n_ft * 0.8)
            fig_dim = cell_size_sum * n_ft * 0.4 + 2
            fig_s, ax_s = plt.subplots(figsize=(fig_dim, fig_dim))
            _heatmap_panel(ax_s, mat, title="", annot=True)
            ax_s.set_title(
                f"Average P-Value\nPaired T-test ({metric.upper()}, {phase}, {label})",
                fontsize=17,
                fontweight="bold",
                pad=6,
            )
            path = PLOTS_DIR / f"ttest_pvalue_summary_{phase}_{label}.png"
            fig_s.savefig(path, dpi=600, bbox_inches="tight")
            plt.close(fig_s)
            print(f"  Saved: {path}")

        def _build_family_summary(model_list: list) -> "pd.DataFrame | None":
            if not model_list:
                return None
            arr = np.stack([model_matrices[m].values for m in model_list], axis=0).astype(float)
            diag = np.eye(n_ft, dtype=bool)
            arr[:, diag] = np.nan
            mean = np.nanmean(arr, axis=0)
            np.fill_diagonal(mean, 1.0)
            return pd.DataFrame(mean, index=all_fold_types, columns=all_fold_types)

        finetuned = [m for m in valid_models if not m.endswith("-gguf")]
        gguf = [m for m in valid_models if m.endswith("-gguf")]

        for family_label, model_list in [("finetuned", finetuned), ("gguf", gguf)]:
            mat = _build_family_summary(model_list)
            if mat is not None:
                _save_summary(mat, family_label)
                if family_label == "finetuned":
                    finetuned_mat = mat

    return finetuned_mat


# ─── Entry point ─────────────────────────────────────────────────────────────


def main() -> None:
    parser = ArgumentParser(description="P-value comparison heatmaps across fold types.")
    parser.add_argument("--results", type=Path, default=INDEX_RESULTS_FILE)
    parser.add_argument("--metric", type=str, default="f1", choices=METRICS)
    parser.add_argument("--phase", type=str, default="both", choices=["test", "holdout", "both"])
    parser.add_argument("--tag", type=str, default=None)
    parser.add_argument("--dataset", type=str, default=None)
    args = parser.parse_args()

    if not args.results.exists():
        print(f"ERROR: Results file not found: {args.results}")
        print("Run `uv run scripts/collect_results.py` first.")
        sys.exit(1)

    print(f"Loading results from {args.results} ...")
    df = load_results(args.results, tag=args.tag, dataset=args.dataset)

    sns.set_theme(style="whitegrid", context="paper")

    phases = PHASES if args.phase == "both" else [args.phase]
    finetuned_mats: dict[str, "pd.DataFrame"] = {}
    cached_metrics: dict[str, pl.DataFrame] = {}   # phase → collected metrics_df

    for phase in phases:
        print(f"\n{'=' * 60}")
        print(f"  Phase: {phase}")
        print(f"{'=' * 60}")

        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            metrics_lf = prepare_per_fold_metrics(df, metric=args.metric, phase=phase)
            try:
                metrics_df = metrics_lf.collect(engine="streaming")
            except Exception:
                metrics_df = metrics_lf.collect()

        if metrics_df.is_empty():
            print(f"  No {phase} data. Skipping.")
            continue

        cached_metrics[phase] = metrics_df

        models = sorted(metrics_df["model"].unique().to_list())
        fold_types = sorted(metrics_df["fold_type"].unique().to_list())
        print(f"  Models: {', '.join(models)}")
        print(f"  Fold types: {', '.join(fold_types)}")

        for col_label, test_col in [("ttest", "P-Value"), ("wilcoxon", "Wilcoxon P-Value")]:
            mat = plot_pvalue_summary(metrics_df, phase, args.metric, test_col, col_label)
            if mat is not None and col_label == "ttest":
                finetuned_mats[phase] = mat

    # Generate LaTeX tables for ttest fine-tuned matrices
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    for phase, mat in finetuned_mats.items():
        fold_types = sorted(mat.index.tolist())
        latex = _build_pvalue_latex_table(mat, fold_types, phase)
        out_path = PLOTS_DIR / f"pvalue_table_{phase}.tex"
        out_path.write_text(latex)
        print(f"  LaTeX p-value table → {out_path}")

    # ── TOST equivalence is now in scripts/plot_tost_grouped.py ───────────────
    # The cross-model TOST was replaced by per-(model, run_mode) paired TOST.
    # See docs/tost_grouped.md and run `uv run scripts/plot_tost_grouped.py`.

    # ── Superiority test (test phase only) ───────────────────────────────────
    print(f"\n{'=' * 60}")
    print("  Superiority Test (test set, H1: random > temporal)")
    print(f"{'=' * 60}")

    test_df = cached_metrics.get("test")
    if test_df is None:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            test_lf = prepare_per_fold_metrics(df, metric=args.metric, phase="test")
            try:
                test_df = test_lf.collect(engine="streaming")
            except Exception:
                test_df = test_lf.collect()

    if test_df is None or test_df.is_empty():
        print("  No test data. Skipping superiority test.")
    else:
        test_f1 = extract_mean_f1_matrix(test_df, metric=args.metric)
        all_test_models = sorted(test_f1.keys())
        ft_models      = [m for m in all_test_models if not m.endswith("-gguf")]
        gguf_t_models  = [m for m in all_test_models if m.endswith("-gguf")]

        for family_label, model_list in [("finetuned", ft_models), ("gguf", gguf_t_models)]:
            if not model_list:
                continue
            print(f"\n  Family: {family_label} ({len(model_list)} models: {', '.join(model_list)})")
            sup_results = run_superiority_pairs(test_f1, model_list)
            if not sup_results:
                print(f"  No superiority results for {family_label}.")
                continue
            for r in sup_results:
                sig_str = "SIG" if r["significant"] else "ns"
                print(
                    f"    {r['label']:30s}  d={r['mean_d']:+6.2f} pp  "
                    f"95% CI [{r['ci_lo']:+.2f}, {r['ci_hi']:+.2f}]  "
                    f"t={r['t_stat']:+.2f}  p_corr={_fmt_pvalue(r['p_corrected'])}  {sig_str}"
                )
            plot_superiority_forest(sup_results, family_label, metric=args.metric)
            write_superiority_latex_table(sup_results, family_label)

    # ── Intra-group comparison (random-vs-random, temporal-vs-temporal) ───────
    print(f"\n{'=' * 60}")
    print("  Intra-group Test (test set, within random / within temporal)")
    print(f"{'=' * 60}")

    if test_df is not None and not test_df.is_empty():
        test_f1 = extract_mean_f1_matrix(test_df, metric=args.metric)
        all_test_models = sorted(test_f1.keys())
        ft_models_ig   = [m for m in all_test_models if not m.endswith("-gguf")]
        gguf_t_models_ig = [m for m in all_test_models if m.endswith("-gguf")]

        for family_label, model_list in [("finetuned", ft_models_ig), ("gguf", gguf_t_models_ig)]:
            if not model_list:
                continue
            print(f"\n  Family: {family_label} ({len(model_list)} models: {', '.join(model_list)})")
            rand_results = run_intragroup_pairs(test_f1, model_list, RANDOM_PAIRS)
            temp_results = run_intragroup_pairs(test_f1, model_list, TEMPORAL_PAIRS)
            for r in rand_results + temp_results:
                sig_str = "SIG" if r["significant"] else "ns"
                equiv_str = "EQUIV" if r["equivalent"] else "not-equiv"
                print(
                    f"    {r['label']:30s}  d={r['mean_d']:+6.2f} pp  "
                    f"90% CI [{r['ci_lo']:+.2f}, {r['ci_hi']:+.2f}]  "
                    f"p_tost={_fmt_pvalue(r['p_tost'])} {equiv_str}  "
                    f"p_diff={_fmt_pvalue(r['p_corrected'])} {sig_str}"
                )
            write_intragroup_latex_table(rand_results, temp_results, family_label)

    print(f"\nAll outputs written to {PLOTS_DIR}")


if __name__ == "__main__":
    main()
