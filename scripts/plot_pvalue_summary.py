def _abbreviate_fold_type(ft: str) -> str:
    """Abbreviate fold type name for heatmap display."""
    if ft.startswith("K-Fold"):
        return "K-Fold"
    elif ft.startswith("Random Growing Window"):
        return "R-GW"
    elif ft.startswith("Random LOO Block"):
        return "R-LOO-B"
    elif ft.startswith("Temporal Growing Window"):
        return "T-GW"
    elif ft.startswith("Temporal LOO Block"):
        return "T-LOO-B"
    else:
        return ft


def _pvalue_colour(p: float) -> str:
    """Interpolate white→red for p-value: white (p=1) to red (p=0)."""
    t = 1.0 - p  # 0 at p=1, 1 at p=0
    r = int(round(255 - t * (255 - 229)))  # 255 → 229 (red channel)
    g = int(round(255 - t * (255 - 87)))   # 255 → 87  (green channel)
    b = int(round(255 - t * (255 - 87)))   # 255 → 87  (blue channel)
    return f"{r:02X}{g:02X}{b:02X}"


def _pvalue_cell(p: float) -> str:
    """Return a coloured cell string: \\cellcolor[HTML]{hex} p-value."""
    if np.isnan(p):
        return "\\cellcolor[HTML]{FFFFFF} ---"
    colour = _pvalue_colour(p)
    return f"\\cellcolor[HTML]{{{colour}}} {p:.3f}"


def _build_pvalue_latex_table(
    mat: "pd.DataFrame",
    fold_types: list[str],
    phase: str,
) -> str:
    """Build a lower-triangular p-value LaTeX table."""
    n_ft = len(fold_types)

    def _short_abbrev(ft: str) -> str:
        return _abbreviate_fold_type(ft)

    col_spec = f"l *{{{n_ft}}}{{c}}"

    lines: list[str] = [
        "% Auto-generated by scripts/plot_pvalue_summary.py - do not edit manually.",
        "% Requires: \\usepackage{booktabs}, \\usepackage{colortbl}, \\usepackage{xcolor}",
        "\\begin{table}[ht]",
        "  \\centering",
        "  \\footnotesize",
        f"  \\begin{{tabular}}{{{col_spec}}}",
        "    \\toprule",
        f"    Fold Type & {' & '.join(f'\\rotatebox{{60}}{{\\footnotesize {_short_abbrev(ft)}}}' for ft in fold_types)} \\\\",
        "    \\midrule",
    ]

    for i, row_ft in enumerate(fold_types):
        row_label = _short_abbrev(row_ft)
        cells = [f"\\texttt{{{row_label}}}"]
        for j, col_ft in enumerate(fold_types):
            if i < j:
                cells.append("\\cellcolor[HTML]{F5F5F5} ---")
            else:
                val = mat.at[row_ft, col_ft] if (row_ft in mat.index and col_ft in mat.columns) else float("nan")
                cells.append(_pvalue_cell(val))
        lines.append(f"    {' & '.join(cells)} \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append(
        "  \\caption{P-values from paired t-tests comparing fold-type performance on the"
        f" \\textbf{{{phase}}} set, fine-tuned models."
        " White (p=1, not significant) $\\to$ red (p≈0, highly significant).}"
    )
    lines.append(f"  \\label{{tab:pvalue_summary_{phase}}}")
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


# ─── TOST helpers ────────────────────────────────────────────────────────────


def _fmt_pvalue(p: float) -> str:
    """Format p-value: '< 0.001' for very small values, 3 decimal places otherwise."""
    if p < 0.001:
        return "< 0.001"
    return f"{p:.3f}"


def _resolve_fold_type(short: str, available: list[str]) -> str | None:
    """Return the first available fold type that starts with the prefix for `short`."""
    prefix = _FOLD_SHORT_TO_PREFIX.get(short, short)
    for ft in available:
        if ft.startswith(prefix):
            return ft
    return None


def paired_tost(
    scores_a: np.ndarray,
    scores_b: np.ndarray,
    delta: float = TOST_DELTA,
    alpha: float = TOST_ALPHA,
) -> tuple[float, float, float, float, float, float]:
    """Paired TOST (Two One-Sided Tests).

    Returns (mean_d, ci_lo, ci_hi, p_lower, p_upper, p_tost).
    90% CI is correct for TOST at α=0.05 (each one-sided test at α=0.05).
    """
    d = scores_a - scores_b
    n = len(d)
    mean_d = float(np.mean(d))
    se = float(np.std(d, ddof=1) / np.sqrt(n))
    df = n - 1

    if se < 1e-12:
        # Zero variance: differences are identical, trivially equivalent
        ci_lo = mean_d
        ci_hi = mean_d
        p_lower = 0.0
        p_upper = 0.0
        p_tost = 0.0
        return mean_d, ci_lo, ci_hi, p_lower, p_upper, p_tost

    t_lower = (mean_d + delta) / se   # H0: mu <= -delta
    t_upper = (mean_d - delta) / se   # H0: mu >= +delta

    p_lower = float(1.0 - t_dist.cdf(t_lower, df))
    p_upper = float(t_dist.cdf(t_upper, df))
    p_tost = max(p_lower, p_upper)

    quantile = float(t_dist.ppf(1.0 - alpha, df))
    ci_lo = mean_d - quantile * se
    ci_hi = mean_d + quantile * se

    return mean_d, ci_lo, ci_hi, p_lower, p_upper, p_tost


def extract_mean_f1_matrix(
    metrics_df: pl.DataFrame,
    metric: str = "f1",
) -> dict[str, dict[str, float]]:
    """Return {model: {fold_type: mean_f1}} averaged across fold numbers."""
    result: dict[str, dict[str, float]] = {}
    for model in metrics_df["model"].unique().to_list():
        model_df = metrics_df.filter(pl.col("model") == model)
        result[model] = {}
        for ft in model_df["fold_type"].unique().to_list():
            vals = model_df.filter(pl.col("fold_type") == ft)[metric].to_numpy().astype(float)
            if len(vals) > 0:
                result[model][ft] = float(np.mean(vals))
    return result


# ─── Superiority test helpers ────────────────────────────────────────────────


def run_superiority_pairs(
    test_f1: dict[str, dict[str, float]],
    models: list[str],
) -> list[dict]:
    """One-sided paired t-test (H1: random > temporal) for each TOST_PAIR.

    Returns list of dicts with keys:
        label, short_a, short_b, n, mean_d, ci_lo, ci_hi,
        t_stat, p_one_sided, p_corrected, significant, direction
    """
    available_fold_types = list({ft for m in models for ft in test_f1.get(m, {})})

    rows: list[dict] = []
    for short_a, short_b in TOST_PAIRS:
        ft_a = _resolve_fold_type(short_a, available_fold_types)
        ft_b = _resolve_fold_type(short_b, available_fold_types)
        if ft_a is None or ft_b is None:
            print(f"  Superiority: skipping pair ({short_a}, {short_b}) - fold type not found")
            continue

        scores_a, scores_b = [], []
        for m in models:
            fa = test_f1.get(m, {}).get(ft_a)
            fb = test_f1.get(m, {}).get(ft_b)
            if fa is not None and fb is not None:
                scores_a.append(fa)
                scores_b.append(fb)

        if len(scores_a) < 2:
            print(f"  Superiority: skipping pair ({short_a}, {short_b}) - fewer than 2 observations")
            continue

        a = np.array(scores_a) * 100.0   # convert to pp
        b = np.array(scores_b) * 100.0
        d = a - b
        n = len(d)
        mean_d = float(np.mean(d))
        se = float(np.std(d, ddof=1) / np.sqrt(n))
        df = n - 1

        if se < 1e-12:
            t_stat = 0.0
            p_one_sided = 0.5
            ci_lo = mean_d
            ci_hi = mean_d
        else:
            t_stat = float(mean_d / se)
            p_one_sided = float(1.0 - t_dist.cdf(t_stat, df))   # upper-tail: H1 random > temporal
            q95 = float(t_dist.ppf(0.975, df))                   # 95% two-sided CI
            ci_lo = mean_d - q95 * se
            ci_hi = mean_d + q95 * se

        rows.append({
            "label":       f"{short_a} vs {short_b}",
            "short_a":     short_a,
            "short_b":     short_b,
            "ft_a":        ft_a,
            "ft_b":        ft_b,
            "n":           n,
            "mean_d":      mean_d,
            "ci_lo":       ci_lo,
            "ci_hi":       ci_hi,
            "t_stat":      t_stat,
            "p_one_sided": p_one_sided,
        })

    if not rows:
        return rows

    p_values = [r["p_one_sided"] for r in rows]
    reject, p_corrected, _, _ = multipletests(p_values, alpha=TOST_ALPHA, method="holm")
    for i, row in enumerate(rows):
        row["p_corrected"] = float(p_corrected[i])
        row["significant"] = bool(p_corrected[i] < TOST_ALPHA)
        row["direction"] = "random > temporal" if row["mean_d"] > 0 else "random ≤ temporal"

    return rows


def plot_superiority_forest(
    sup_results: list[dict],
    family_label: str,
    metric: str = "f1",
) -> Path | None:
    """Forest plot for one-sided superiority test (test-set F1 differences)."""
    if not sup_results:
        return None

    labels = [r["label"] for r in sup_results]
    means  = [r["mean_d"]  for r in sup_results]
    lo     = [r["ci_lo"]   for r in sup_results]
    hi     = [r["ci_hi"]   for r in sup_results]
    sig    = [r["significant"] for r in sup_results]

    n = len(labels)
    y_pos = list(range(n))

    fig, ax = plt.subplots(figsize=(8, max(3, n * 1.1 + 1.5)))

    for i, (mean, lo_i, hi_i, is_sig) in enumerate(zip(means, lo, hi, sig)):
        color = "#2166ac" if is_sig else "#d6604d"
        ax.errorbar(
            mean, i,
            xerr=[[mean - lo_i], [hi_i - mean]],
            fmt="o",
            color=color,
            ecolor=color,
            capsize=5,
            markersize=8,
            linewidth=2,
        )

    ax.axvline(0, color="black", linestyle="--", linewidth=1.2, label="No effect (0 pp)")

    from matplotlib.lines import Line2D
    legend_handles = [
        Line2D([0], [0], marker="o", color="w", markerfacecolor="#2166ac", markersize=9,
               label="Significant (random > temporal, Holm–Bonferroni)"),
        Line2D([0], [0], marker="o", color="w", markerfacecolor="#d6604d", markersize=9,
               label="Not significant"),
        Line2D([0], [0], color="black", linestyle="--", label="No effect (0 pp)"),
    ]
    ax.legend(handles=legend_handles, loc="lower right", fontsize=9)

    ax.set_yticks(y_pos)
    ax.set_yticklabels(labels, fontsize=11)
    ax.set_xlabel("Mean test F1 difference (random − temporal, pp)", fontsize=11)
    ax.set_title(
        f"Superiority Test - Test F1 (H₁: random > temporal, Holm–Bonferroni)",
        fontsize=12,
        fontweight="bold",
    )
    ax.grid(axis="x", alpha=0.3)
    plt.tight_layout()

    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = PLOTS_DIR / f"superiority_forest_{family_label}.png"
    fig.savefig(out_path, dpi=600, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out_path}")
    return out_path


