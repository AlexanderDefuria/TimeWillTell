def run_intragroup_pairs(
    test_f1: dict[str, dict[str, float]],
    models: list[str],
    pairs: list[tuple[str, str]],
) -> list[dict]:
    """Two-sided paired t-test + TOST for within-group fold-type pairs (cross-model).

    Each observation is one model's mean F1 for that fold type.
    Returns list of dicts with keys:
        label, short_a, short_b, n, mean_d, ci_lo, ci_hi,
        t_stat, p_two_sided, p_corrected, significant,
        p_tost, equivalent
    """
    available_fold_types = list({ft for m in models for ft in test_f1.get(m, {})})

    rows: list[dict] = []
    for short_a, short_b in pairs:
        ft_a = _resolve_fold_type(short_a, available_fold_types)
        ft_b = _resolve_fold_type(short_b, available_fold_types)
        if ft_a is None or ft_b is None:
            print(f"  Intra-group: skipping pair ({short_a}, {short_b}) - fold type not found")
            continue

        scores_a, scores_b = [], []
        for m in models:
            fa = test_f1.get(m, {}).get(ft_a)
            fb = test_f1.get(m, {}).get(ft_b)
            if fa is not None and fb is not None:
                scores_a.append(fa)
                scores_b.append(fb)

        if len(scores_a) < 2:
            print(f"  Intra-group: skipping pair ({short_a}, {short_b}) - fewer than 2 observations")
            continue

        a = np.array(scores_a) * 100.0
        b = np.array(scores_b) * 100.0
        n = len(a)

        # Two-sided paired t-test (95% CI)
        d = a - b
        mean_d = float(np.mean(d))
        se = float(np.std(d, ddof=1) / np.sqrt(n))
        df = n - 1
        if se < 1e-12:
            t_stat = 0.0
            p_two_sided = 1.0
            ci_lo_95 = mean_d
            ci_hi_95 = mean_d
        else:
            t_stat = float(mean_d / se)
            p_two_sided = float(2.0 * t_dist.cdf(-abs(t_stat), df))
            q975 = float(t_dist.ppf(0.975, df))
            ci_lo_95 = mean_d - q975 * se
            ci_hi_95 = mean_d + q975 * se

        # TOST (90% CI, α=0.05)
        tost_mean_d, ci_lo_90, ci_hi_90, p_lower, p_upper, p_tost = paired_tost(a, b)

        rows.append({
            "label":        f"{short_a} vs {short_b}",
            "short_a":      short_a,
            "short_b":      short_b,
            "ft_a":         ft_a,
            "ft_b":         ft_b,
            "n":            n,
            "mean_d":       mean_d,
            "ci_lo":        ci_lo_90,
            "ci_hi":        ci_hi_90,
            "t_stat":       t_stat,
            "p_two_sided":  p_two_sided,
            "p_tost":       p_tost,
            "equivalent":   bool(p_tost < TOST_ALPHA),
        })

    if not rows:
        return rows

    p_values = [r["p_two_sided"] for r in rows]
    reject, p_corrected, _, _ = multipletests(p_values, alpha=TOST_ALPHA, method="holm")
    for i, row in enumerate(rows):
        row["p_corrected"] = float(p_corrected[i])
        row["significant"] = bool(p_corrected[i] < TOST_ALPHA)

    return rows


