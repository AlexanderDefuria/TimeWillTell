#!/usr/bin/env python3
"""Generate dataset summary LaTeX tables for paper documentation."""

import subprocess
import sys
from pathlib import Path

import polars as pl

try:
    from scripts import DATASETS_DIR
    from scripts.plot_results import _f1_colour
except ModuleNotFoundError:
    sys.path.append(str(Path(__file__).resolve().parents[1]))
    from scripts import DATASETS_DIR
    from scripts.plot_results import _f1_colour

PLOTS_DIR = Path(__file__).resolve().parents[1] / "data" / "plots" / "0_dataset_summary"


def _colour_cell(text: str, val: float, vmin: float, vmax: float) -> str:
    """Return a coloured cell string: \\cellcolor[HTML]{hex} <text>"""
    colour = _f1_colour(val, vmin, vmax)
    return f"\\cellcolor[HTML]{{{colour}}} {text}"


def generate_megavul_overview() -> str:
    """Generate LaTeX table for megavul dataset overview statistics."""
    df = pl.read_parquet(DATASETS_DIR / "megavul.parquet")
    total = len(df)

    vuln_dist = df.group_by("vulnerability").agg(pl.len().alias("count"))
    vuln_filtered = vuln_dist.filter(pl.col("vulnerability") == 1)
    safe_filtered = vuln_dist.filter(pl.col("vulnerability") == 0)
    vuln_count = vuln_filtered.row(0, named=True)["count"] if not vuln_filtered.is_empty() else 0
    safe_count = safe_filtered.row(0, named=True)["count"] if not safe_filtered.is_empty() else 0

    date_range_start = str(df.select("publish_date").min()[0, 0])
    date_range_end = str(df.select("publish_date").max()[0, 0])

    func_lengths = df.select(
        pl.col("func_before").str.len_bytes().fill_null(0).alias("length")
    ).to_series()
    avg_len = float(func_lengths.mean())
    median_len = float(func_lengths.median())
    max_len = int(func_lengths.max())
    min_len = int(func_lengths.min())

    unique_repos = df["repo_name"].n_unique()

    cwe_data = df.select("cwe_ids").to_series().explode()
    cwe_counts = cwe_data.value_counts().sort("count", descending=True).head(15)

    # Abbreviate years: 1999 → '99, 2024 → '24
    start_date = date_range_start.split('T')[0]
    end_date = date_range_end.split('T')[0]
    start_year = start_date[:4]
    end_year = end_date[:4]
    start_date_abbr = f"'{start_year[2:4]}-{start_date[5:]}"
    end_date_abbr = f"'{end_year[2:4]}-{end_date[5:]}"
    date_range = f"{start_date_abbr} to {end_date_abbr}"

    lines = [
        "% Auto-generated by scripts/plot_dataset_summary.py — do not edit manually.",
        "% Requires: \\usepackage{booktabs}, \\usepackage{colortbl}, \\usepackage{xcolor}, \\usepackage{makecell}",
        "\\begin{table}[ht]",
        "  \\centering",
        "  \\footnotesize",
        "  \\begin{tabular}{l l l l l l}",
        "    \\toprule",
        "    \\makecell[l]{\\textbf{Total}\\\\\\textbf{Samples}} & \\makecell[l]{\\textbf{Vuln.}\\\\\\textbf{Count}} & \\makecell[l]{\\textbf{Unique}\\\\\\textbf{Repos}} & \\makecell[l]{\\textbf{Date}\\\\\\textbf{Range}} & \\makecell[l]{\\textbf{Avg.}\\\\\\textbf{Func. Len.}} & \\makecell[l]{\\textbf{Median}\\\\\\textbf{Func. Len.}} \\\\",
        "    \\midrule",
        f"    {total:,} & {vuln_count:,} ({100*vuln_count/total:.1f}\\%) & {unique_repos:,} & {date_range} & {avg_len:.0f} chars & {median_len:.0f} chars \\\\",
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\caption{MegaVul dataset statistics for source code vulnerability detection.}",
        "  \\label{tab:dataset_megavul}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def generate_cwe_distribution() -> str:
    """Generate LaTeX table for top 15 CWEs in megavul with colour scale."""
    df = pl.read_parquet(DATASETS_DIR / "megavul.parquet")

    cwe_data = df.select("cwe_ids").to_series().explode()
    cwe_counts = cwe_data.value_counts().sort("count", descending=True).head(15)

    counts = [row[1] for row in cwe_counts.iter_rows()]
    vmin, vmax = min(counts), max(counts)

    lines = [
        "% Auto-generated by scripts/plot_dataset_summary.py — do not edit manually.",
        "% Requires: \\usepackage{booktabs}, \\usepackage{colortbl}, \\usepackage{xcolor}",
        "\\begin{table}[ht]",
        "  \\centering",
        "  \\footnotesize",
        "  \\begin{tabular}{l r r}",
        "    \\toprule",
        "    \\textbf{CWE ID} & \\textbf{Count} & \\textbf{\\%} \\\\",
        "    \\midrule",
    ]

    total_vulnerable = sum(counts)
    for row in cwe_counts.iter_rows(named=True):
        cwe_id = row.get("cwe_ids")
        count = row.get("count")
        pct = 100 * count / total_vulnerable if total_vulnerable > 0 else 0
        count_cell = _colour_cell(f"{count:,}", float(count), float(vmin), float(vmax))
        lines.append(f"    {cwe_id} & {count_cell} & {pct:.1f}\\% \\\\")

    lines.extend([
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\caption{Top 15 CWE types in MegaVul (colour scale: white = low frequency, green = high frequency).}",
        "  \\label{tab:cwe_distribution}",
        "\\end{table}",
    ])
    return "\n".join(lines) + "\n"


def main() -> None:
    """Generate and save LaTeX tables."""
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)

    overview_latex = generate_megavul_overview()
    overview_path = PLOTS_DIR / "dataset_overview.tex"
    overview_path.write_text(overview_latex)
    print(f"✓ Saved: {overview_path}")

    cwe_latex = generate_cwe_distribution()
    cwe_path = PLOTS_DIR / "dataset_cwe_distribution.tex"
    cwe_path.write_text(cwe_latex)
    print(f"✓ Saved: {cwe_path}")

    print("\nTex files ready for inclusion in paper. Example:")
    print("  \\input{data/plots/0_dataset_summary/dataset_overview.tex}")
    print("  \\input{data/plots/0_dataset_summary/dataset_cwe_distribution.tex}")


if __name__ == "__main__":
    main()
